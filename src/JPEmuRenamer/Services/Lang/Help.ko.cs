# 자동 미리보기
"플레이" 탭에서 게임을 선택하고 잠시 멈추면 오른쪽 위에 그 게임의 영상이 자동으로 재생됩니다. 내장 코어를 소리·입력 없이 돌려 타이틀 화면 뒤에 시작되는 데모를 보여 줍니다. 미리보기에는 그 기종의 내장 코어가 다운로드되어 있어야 합니다.

| 항목 | 기본값 |
| 재생 시작 | 선택하고 0.3초 멈추면(커서를 연타하는 동안에는 시작하지 않음) |
| 재생 속도 | 4배속 |
| 처음 건너뛰기 | 실행 후 10초(제작사 로고 등을 건너뜀) |
| 처음부터 반복까지 | 60초 |
| 소리·입력 | 없음(세이브 데이터에도 손대지 않음) |

