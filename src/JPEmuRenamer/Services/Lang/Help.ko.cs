## 상태의 의미
| 상태 | 의미 | 이름 변경 |
| 일치 | CRC32가 일치하고 이름도 DAT와 같음 | 불필요 |
| 이름 다름 | CRC32가 일치하고 이름이 DAT와 다름 | 대상 |
| 중복 | 같은 게임의 파일이 이미 있음 | 하지 않음 |
| DAT에 없음 | DAT에 CRC32가 없음 | 하지 않음 |
| 미보유 | DAT에는 있지만 파일이 없음 | ― |

# 이름 변경 순서
- "이름 변경" 탭에서 "이름 다름" 행을 확인합니다(처음에는 모두 체크되어 있음)
- 바꾸고 싶지 않은 행은 체크를 해제합니다. 머리글의 체크로 한꺼번에 바꿀 수 있습니다
- 오른쪽에 선택한 행의 "변경 전"과 "변경 후"가 표시되므로 내용을 확인합니다
- 아래쪽의 "이름 변경 실행"을 누르고 확인에서 "예"를 고릅니다
- 끝나면 건수가 표시되고 목록이 자동으로 갱신됩니다

> CRC32가 DAT와 일치한 파일만 바꿉니다. 같은 이름의 파일이 이미 있으면 건너뜁니다.

## ZIP 안의 ROM 이름
"설정" → "ZIP 안의 ROM 이름도 변경"이 켜져 있으면 ZIP 파일 이름과 함께 안의 ROM 이름도 DAT 이름으로 바꿉니다.

## Windows에서 쓸 수 없는 문자
`\` `/` `:` `*` `?` `"` `<` `>` `|`는 같은 모양의 전각 문자로 바꿉니다.

# 되돌리기
"이름 변경" 탭 아래쪽의 "되돌리기"로 마지막에 실행한 이름 변경을 한 번에 통째로 되돌릴 수 있습니다. 다시 누르면 그 전 회차를 되돌릴 수 있습니다(최근 50회까지).

> "되돌리기"는 기종과 관계없이 마지막에 실행한 회차가 대상입니다. 확인 화면에 날짜와 건수가 표시됩니다.

