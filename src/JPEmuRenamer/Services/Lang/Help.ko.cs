# 이름 변경의 원리
ROM의 내용에서 CRC32(파일의 지문 같은 값)를 계산해 DAT 파일(게임 이름과 CRC32 목록)과 대조합니다. 일치한 파일만 DAT에 적힌 올바른 이름으로 바꿉니다. 파일 이름이 아무리 제각각이어도 내용이 같으면 정확히 판정할 수 있습니다.

> 이름을 바꾸기 전에 반드시 목록에서 확인할 수 있고, 실행한 뒤에도 "되돌리기"로 한 번에 되돌릴 수 있습니다.

# 준비
## DAT 파일 준비
OfflineList 형식의 DAT 파일(XML)을 사용합니다. 기종마다 준비하세요. 오래된 Shift-JIS DAT도 지원합니다.

## 기종 설정
왼쪽 기종 목록에서 기종을 선택하고 "기종 설정"에서 다음을 지정합니다.

| 항목 | 내용 |
| DAT 파일 | 준비한 DAT 파일 |
| ROM 폴더 | ROM을 넣어 둔 폴더(여러 개는 `;`로 구분) |
| 확장자 | 읽을 확장자(예: `.nes;.zip`) |
| 헤더 처리 | iNES·FDS 등의 헤더를 CRC32 계산에 포함할지(보통은 "자동") |

설정하면 ROM 읽기와 대조가 자동으로 시작됩니다. 두 번째부터는 바뀌지 않은 파일의 계산을 건너뛰므로 금방 끝납니다.

