## 스냅샷
- 미리보기 중 오른쪽 아래의 "이 화면 저장"을 누르면 그 순간을 스냅샷으로 저장합니다
- 게임을 오른쪽 클릭 → "이 기종의 스냅샷 일괄 생성…"으로 기종 안의 모든 ROM을 뒤에서 차례로 실행해 지정한 시점(기본 30초)의 화면을 한꺼번에 저장합니다. 스냅샷이 있는 게임은 건너뛸 수 있습니다
- 스냅샷은 미리보기가 시작되기 전과, 화면이 한동안 움직이지 않는 게임(데모가 없는 게임)에서 표시됩니다
