# 重新命名的運作方式
應用程式會計算每個 ROM 的 CRC32（內容的指紋），並與 DAT 檔（標題與 CRC32 的清單）比對。只有相符的檔案會被改成 DAT 中正確的名稱，不論目前叫什麼名字。

> 重新命名前一定會先確認清單，之後也能用「復原」整批還原。

# 準備
## 取得 DAT 檔
請為每台主機準備 OfflineList 格式（XML）的 DAT。也支援舊的 Shift-JIS DAT。

## 設定主機
在左側選擇主機，並在「主機設定」中設定以下項目。

| 項目 | 說明 |
| DAT 檔 | DAT 檔案 |
| ROM 資料夾 | 存放 ROM 的資料夾（以 `;` 分隔） |
| 副檔名 | 要讀取的副檔名（例如 `.nes;.zip`） |
| 檔頭處理 | CRC32 是否包含 iNES/FDS 檔頭（通常用「自動」） |

讀取與比對會自動開始。第二次之後會略過沒有變更的檔案，所以很快。

# 「重新命名」分頁
切換到上方的「重新命名」分頁即可看到表格。

| 欄位 | 說明 |
| ✓ | 是否重新命名（只有「需重新命名」的列可以勾選） |
| 狀態 | 比對結果（見下方） |
| 目前檔名 | 現在的名稱 |
| → DAT 中的名稱 | 重新命名後的名稱 |
| CRC32／大小／格式 | ROM 資訊 |

## 狀態
| 狀態 | 意義 | 是否重新命名 |
| 正確 | CRC32 相符，名稱也正確 | 不需要 |
| 需重新命名 | CRC32 相符，但名稱不同 | 是 |
| 重複 | 同一個標題已有檔案 | 否 |
| 不在 DAT 中 | DAT 中沒有這個 CRC32 | 否 |
| 未擁有 | DAT 中有，但你沒有這個檔案 | ― |

# 重新命名的步驟
- 在「重新命名」分頁確認「需重新命名」的列（一開始全部勾選）
- 取消不想重新命名的項目。表頭的核取方塊可一次切換全部
- 右側會顯示所選列的「變更前」與「變更後」
- 按下方的「重新命名」，再按「是」確認
- 會顯示件數，清單也會自動更新

> 只有 CRC32 與 DAT 相符的檔案會被變更。若新名稱的檔案已存在，該檔案會被略過。

## ZIP 內的 ROM 名稱
開啟「設定」→「同時重新命名 ZIP 內的 ROM」後，每個 ZIP 內的 ROM 會跟著 ZIP 一起重新命名。

## Windows 不允許的字元
`\` `/` `:` `*` `?` `"` `<` `>` `|` 會被換成全形字元。

# 復原
「重新命名」分頁下方的「復原」會整批還原最近一次的執行。再按一次會還原再前一次（最多到最近 50 次）。

> 「復原」一律還原最新的一次，與主機無關。確認視窗會顯示日期與檔案數。

