| 功能 | 用法 |
| 已擁有／全部／未擁有 | 篩選清單。「未擁有」會顯示你還沒有的遊戲 |
| 搜尋 | 在搜尋框輸入文字，依標題或檔名篩選 |
| 重新比對 | 新增或移除 ROM 後使用 |
| 隱藏副檔名 | 「設定」→「在遊戲清單中隱藏副檔名（.zip 等）」 |
| 讀取子資料夾 | 「設定」→「也讀取子資料夾」 |
| 只顯示 DAT 名稱 | 用於改了檔名模擬器就無法執行的街機。在「主機設定」中開啟後，會保留檔名並在清單中顯示 DAT 名稱 |

# 疑難排解
| 問題 | 檢查事項 |
| 完全沒有相符 | 確認 DAT 是否屬於正確的主機。把「檔頭處理」改成「包含檔頭」或「排除檔頭」可能會有幫助 |
| 「無法讀取 DAT 檔」 | 確認是 OfflineList 的 DAT（XML） |
| 「重複」 | 你有兩個以上同一標題的 ROM。請把其中一個移到其他資料夾 |
| 顯示「（已存在）」並略過 | 新名稱的檔案已經存在。決定要保留哪一個後手動整理 |
| ZIP 內的名稱沒有改變 | 若 ZIP 本身的名稱已經正確，內部的名稱會維持不變 |
