## ตั้งค่าเครื่อง
เลือกเครื่องทางซ้าย แล้วตั้งค่าต่อไปนี้ใน "ตั้งค่าเครื่อง"

| รายการ | คำอธิบาย |
| ไฟล์ DAT | ไฟล์ DAT |
| โฟลเดอร์ ROM | โฟลเดอร์ที่เก็บ ROM (คั่นด้วย `;`) |
| นามสกุลไฟล์ | นามสกุลที่จะอ่าน (เช่น `.nes;.zip`) |
| การจัดการส่วนหัว | จะรวมส่วนหัว iNES/FDS ใน CRC32 หรือไม่ (ปกติใช้ "อัตโนมัติ") |

การอ่านและเทียบจะเริ่มเองอัตโนมัติ ตั้งแต่ครั้งที่สองเป็นต้นไป ไฟล์ที่ไม่เปลี่ยนจะถูกข้าม จึงเร็ว

# แท็บ "เปลี่ยนชื่อ"
สลับไปที่แท็บ "เปลี่ยนชื่อ" ด้านบนเพื่อดูตาราง

| คอลัมน์ | คำอธิบาย |
| ✓ | จะเปลี่ยนชื่อหรือไม่ (เลือกได้เฉพาะแถว "ต้องเปลี่ยนชื่อ") |
| สถานะ | ผลการเทียบ (ดูด้านล่าง) |
| ชื่อไฟล์ปัจจุบัน | ชื่อตอนนี้ |
| → ชื่อใน DAT | ชื่อหลังเปลี่ยน |
| CRC32 / ขนาด / รูปแบบ | ข้อมูล ROM |

## สถานะ
| สถานะ | ความหมาย | เปลี่ยนชื่อ |
| ถูกต้อง | CRC32 ตรงกันและชื่อถูกต้องแล้ว | ไม่ต้อง |
| ต้องเปลี่ยนชื่อ | CRC32 ตรงกันแต่ชื่อต่างกัน | ใช่ |
| ซ้ำ | มีไฟล์ของเกมเดียวกันอยู่แล้ว | ไม่ |
| ไม่มีใน DAT | ไม่มี CRC32 นี้ใน DAT | ไม่ |
| ยังไม่มี | มีใน DAT แต่คุณไม่มีไฟล์ | ― |

# เปลี่ยนชื่อทีละขั้นตอน
- ในแท็บ "เปลี่ยนชื่อ" ให้ตรวจแถว "ต้องเปลี่ยนชื่อ" (ตอนแรกถูกเลือกไว้ทั้งหมด)
- เอาเครื่องหมายออกจากแถวที่ไม่ต้องการเปลี่ยน กล่องที่หัวคอลัมน์ใช้สลับทั้งหมดได้
- ทางขวาจะแสดง "ก่อน" และ "หลัง" ของแถวที่เลือก
- กด "เปลี่ยนชื่อ" ด้านล่าง แล้วยืนยันด้วย "ใช่"
- จำนวนจะแสดงขึ้นมา และรายการจะอัปเดตเอง

> จะเปลี่ยนเฉพาะไฟล์ที่ CRC32 ตรงกับ DAT ถ้ามีไฟล์ชื่อใหม่อยู่แล้ว ไฟล์นั้นจะถูกข้าม

## ชื่อ ROM ในไฟล์ ZIP
ถ้าเปิด "การตั้งค่า" → "เปลี่ยนชื่อ ROM ในไฟล์ ZIP ด้วย" ROM ใน ZIP แต่ละไฟล์จะถูกเปลี่ยนชื่อไปพร้อมกับ ZIP

