# เลิกทำ
"เลิกทำ" ที่ด้านล่างของแท็บ "เปลี่ยนชื่อ" จะย้อนกลับการทำครั้งล่าสุดทั้งหมด กดอีกครั้งเพื่อย้อนครั้งก่อนหน้า (ได้ถึง 50 ครั้งล่าสุด)

> "เลิกทำ" จะย้อนการทำครั้งล่าสุดเสมอ ไม่ว่าเป็นเครื่องใด หน้าต่างยืนยันจะแสดงวันที่และจำนวนไฟล์

