# Автопросмотр
На вкладке «Играть» выберите игру и немного подождите — справа вверху начнёт проигрываться видео игры. Встроенное ядро работает без звука и управления и показывает демо, которое идёт после титульного экрана. Встроенное ядро системы должно быть установлено.

| Параметр | По умолчанию |
