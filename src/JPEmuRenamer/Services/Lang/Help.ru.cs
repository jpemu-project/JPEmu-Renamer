# Переименование по шагам
- На вкладке «Переименование» проверьте строки «Переименовать» (сначала все отмечены)
- Снимите отметку с тех, что не нужно переименовывать. Флажок в заголовке переключает все сразу
- Справа показаны «До» и «После» для выбранной строки
- Нажмите «Переименовать» внизу и подтвердите кнопкой «Да»
- Будет показано количество, и список обновится сам

> Изменяются только файлы, чей CRC32 совпал с DAT. Файл пропускается, если файл с новым именем уже существует.

## Имена ROM внутри ZIP
Если в «Настройках» включено «Переименовывать и ROM внутри ZIP», ROM в каждом ZIP переименовывается вместе с ZIP.

## Символы, запрещённые в Windows
`\` `/` `:` `*` `?` `"` `<` `>` `|` заменяются полноширинными аналогами.

# Отмена
«Отменить» внизу вкладки «Переименование» целиком возвращает последнюю операцию. Нажмите ещё раз, чтобы вернуть предыдущую (до 50 последних).

> «Отменить» возвращает самую свежую операцию независимо от системы. В подтверждении указаны её дата и число файлов.

