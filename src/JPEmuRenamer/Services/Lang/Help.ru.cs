## Снимки
- Во время автопросмотра кнопка «Сохранить этот экран» справа внизу сохраняет этот момент как снимок
- Правый щелчок по игре → «Создать снимки для этой системы…» по очереди запускает в фоне все ROM системы и сохраняет экран в заданный момент (по умолчанию на 30-й секунде). Игры, у которых снимок уже есть, можно пропустить
- Снимки показываются до начала автопросмотра и для игр, у которых экран не меняется
- Они сохраняются как `snapshots\<система>\<название>.png` в папке настроек

> Запуск игры во время автопросмотра или создания снимков сначала останавливает автопросмотр.

