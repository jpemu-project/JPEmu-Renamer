# Как работает переименование
Приложение вычисляет CRC32 (отпечаток содержимого) каждого ROM и сверяет его с файлом DAT (списком названий и CRC32). Переименовываются только совпавшие файлы — в правильное имя из DAT, как бы они ни назывались сейчас.

> Перед переименованием вы всегда проверяете список, а «Отменить» потом возвращает всю операцию целиком.

# Подготовка
## Файл DAT
Используйте DAT в формате OfflineList (XML) для каждой системы. Поддерживаются и старые DAT в Shift-JIS.

## Настройка системы
Выберите систему слева и задайте в «Настройках системы» следующее.

| Параметр | Описание |
| Файл DAT | Файл DAT |
| Папки с ROM | Папки, где лежат ROM (через `;`) |
| Расширения | Читаемые расширения (например, `.nes;.zip`) |
| Обработка заголовка | Учитывать ли заголовки iNES/FDS в CRC32 (обычно «Авто») |

Чтение и сверка начинаются автоматически. Со второго раза неизменённые файлы пропускаются, так что это быстро.

