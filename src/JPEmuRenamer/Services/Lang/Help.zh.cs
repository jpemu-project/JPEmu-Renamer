| 功能 | 用法 |
| 仅已拥有 / 全部 / 仅未拥有 | 在列表上方筛选要显示的游戏。“仅未拥有”可以看到还没有的游戏 |
| 搜索 | 在上方搜索框输入，按游戏名和文件名筛选 |
