# 重命名的原理
根据 ROM 的内容计算 CRC32（类似文件指纹的值），并与 DAT 文件（游戏名称与 CRC32 的列表）对照。只有一致的文件才会改成 DAT 中写的正确名称。无论文件名多么杂乱，只要内容相同就能正确判断。

> 重命名前一定可以在列表中确认，执行后也能用“撤销”整次恢复。

# 准备
## 准备 DAT 文件
使用 OfflineList 格式的 DAT 文件（XML）。请为每个机种准备一个。也支持旧的 Shift-JIS DAT。

## 设置机种
在左侧机种列表中选择机种，在“机种设置”中指定以下内容。

| 项目 | 内容 |
| DAT 文件 | 准备好的 DAT 文件 |
| ROM 文件夹 | 存放 ROM 的文件夹（多个用 `;` 分隔） |
| 扩展名 | 要读取的扩展名（例如：`.nes;.zip`） |
| 文件头处理 | 计算 CRC32 时是否包含 iNES・FDS 等文件头（通常选“自动”） |

设置后会自动开始读取 ROM 并比对。第二次起会跳过没有变化的文件，所以很快就能完成。

# 重命名标签页的说明
切换到上方的“重命名”标签页，会显示管理表。

| 列 | 内容 |
| ✓ | 是否重命名（只有“名称不同”的行可以选） |
| 状态 | 比对结果（见下表） |
| 当前文件名 | 现在的文件名 |
| → DAT 中的名称 | 重命名后的文件名 |
| CRC32・大小・格式 | ROM 的信息 |

## 状态的含义
| 状态 | 含义 | 重命名 |
| 一致 | CRC32 一致，名称也与 DAT 相同 | 不需要 |
| 名称不同 | CRC32 一致，名称与 DAT 不同 | 对象 |
| 重复 | 已经有同一游戏的文件 | 不进行 |
| DAT 中没有 | DAT 中没有这个 CRC32 | 不进行 |
| 未拥有 | DAT 中有，但手上没有文件 | ― |

# 重命名的步骤
- 在“重命名”标签页确认“名称不同”的行（一开始全部已勾选）
- 不想重命名的行请取消勾选。用表头的勾选框可以一次切换全部
- 右侧会显示所选行的“修改前”和“修改后”，请确认内容
- 按下方的“执行重命名”，在确认中选“是”
- 完成后会显示数量，列表会自动更新

> 只修改 CRC32 与 DAT 一致的文件。已存在同名文件时会跳过。

## ZIP 内的 ROM 名称
“设置”→“同时重命名 ZIP 内的 ROM”打开时，会在修改 ZIP 文件名的同时，把其中的 ROM 名称也改成 DAT 中的名称。

## Windows 不能使用的字符
`\` `/` `:` `*` `?` `"` `<` `>` `|` 会被替换为形状相同的全角字符。

# 撤销
“重命名”标签页下方的“撤销”可以把最近一次执行的重命名整次恢复。再按一次可以恢复更早的一次（最多保留最近 50 次）。

> “撤销”与机种无关，针对的是最后执行的那一次。确认画面会显示日期时间和数量。

