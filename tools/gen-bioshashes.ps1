# libretro-database の dat/System.dat から、アプリに入れる BiosHashes.txt（BIOSの指紋とファイル名の表）を作る。
# BiosHashes.txt は System.dat から作ったものなので、System.dat と同じ CC BY-SA 4.0 で配布する。
#
# 使い方:
#   1. https://raw.githubusercontent.com/libretro/libretro-database/master/dat/System.dat を用意する
#   2. pwsh tools/gen-bioshashes.ps1 -SystemDat <System.dat の場所>
param(
    [Parameter(Mandatory)] [string] $SystemDat,
    [string] $Out = (Join-Path $PSScriptRoot '..\src\JPEmuRenamer\Emulation\BiosHashes.txt')
)
$ErrorActionPreference = 'Stop'
$text = [IO.File]::ReadAllText($SystemDat)
$version = if ($text -match 'version\s+(\S+)') { $Matches[1] } else { '?' }
$re = [regex]'rom \(\s*name\s+(?:"(?<n>[^"]+)"|(?<n>\S+))\s+size\s+(?<s>\d+)\s+crc\s+\w+\s+md5\s+(?<m>[0-9a-fA-F]{32})'
$rows = foreach ($m in $re.Matches($text)) {
    "{0}`t{1}`t{2}" -f $m.Groups['m'].Value.ToLowerInvariant(), $m.Groups['s'].Value, $m.Groups['n'].Value
}
$rows = $rows | Sort-Object -Unique
$header = @(
    "# BIOS fingerprints (md5, size, file name) used by libretro cores."
    "# Derived from libretro-database dat/System.dat $version (https://github.com/libretro/libretro-database)"
    "# by libretro, licensed under CC BY-SA 4.0 (https://creativecommons.org/licenses/by-sa/4.0/)."
    "# Only the md5, size and name columns were kept. Generated by tools/gen-bioshashes.ps1."
)
$utf8 = New-Object Text.UTF8Encoding($false)
[IO.File]::WriteAllText($Out, (($header + $rows) -join "`n") + "`n", $utf8)
Write-Host "$($rows.Count) rows -> $Out"
